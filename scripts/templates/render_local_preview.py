#!/usr/bin/env python3
"""Render a prepared local CALMA bundle with FFmpeg; no models or services.
Never overwrites a source or an existing output. The bundle must be generated by
prepare_local_preview.mjs. Open Sans is supplied in bundle/fonts with its license.
"""
import argparse
import hashlib
import json
import os
import pathlib
import subprocess
import tempfile


def probe(path):
    return json.loads(subprocess.check_output(['ffprobe', '-v', 'error', '-show_streams', '-show_format', '-of', 'json', str(path)], text=True))


def digest(path):
    with path.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def render(source, bundle, output):
    source = source.resolve(strict=True)
    bundle = bundle.resolve(strict=True)
    output = output.resolve()
    if not source.is_file() or source == output or output.exists() or output.with_suffix('.audit.json').exists():
        raise ValueError('Source must be a local file and output must be new and distinct')
    manifest = json.loads((bundle / 'manifest.json').read_text())
    if manifest.get('kind') != 'local-preview' or manifest.get('productionReady') is not False:
        raise ValueError('Expected a prepared local preview bundle')
    info = probe(source)
    video = next(s for s in info['streams'] if s['codec_type'] == 'video')
    audio = [s for s in info['streams'] if s['codec_type'] == 'audio']
    rotation = next((s.get('rotation', 0) for s in video.get('side_data_list', []) if 'rotation' in s), 0)
    w, h = video['width'], video['height']
    if abs(rotation) % 180 == 90:
        w, h = h, w
    expected = manifest['source']
    if (w, h) != (expected['width'], expected['height']) or abs(float(info['format']['duration']) - expected['duration']) > .05:
        raise ValueError('Source dimensions/duration do not match camera and transcript')
    bound_media = []
    for decision in manifest.get('selectedMedia', []):
        media = pathlib.Path(decision['localFile']).resolve(strict=True)
        if not media.is_file():
            raise ValueError('B-roll binding must be a local file')
        details = probe(media)
        stream = next((s for s in details['streams'] if s['codec_type'] == 'video'), None)
        if stream is None or float(stream.get('duration', details['format']['duration'])) + 1e-6 < decision['sourceOut']:
            raise ValueError('B-roll media is missing video or too short')
        bound_media.append({'path': media, 'sha256': digest(media), 'assetId': decision['assetId']})
    illustrations = []
    for item in manifest.get('illustrations', []):
        media = pathlib.Path(item['localFile']).resolve(strict=True)
        if item.get('rights') not in ('owned', 'licensed') or item.get('role') != 'illustration' or item.get('sourceSha256') != manifest['source'].get('sha256'):
            raise ValueError('Illustration provenance invalid')
        details = probe(media)
        stream = next((s for s in details['streams'] if s['codec_type'] == 'video'), None)
        if stream is None or stream['codec_name'] not in ('png', 'mjpeg', 'webp', 'bmp') or digest(media) != item['sha256']:
            raise ValueError('Illustration must be a verified still image')
        illustrations.append({'path': media, 'sha256': item['sha256'], 'assetId': item['assetId']})
    subject_layers = []
    for item in manifest.get('subjectLayers', []):
        matte = item.get('matte', {})
        resource = pathlib.Path(item['localFile']).resolve(strict=True)
        mask = pathlib.Path(matte['localFile']).resolve(strict=True)
        if item.get('sourceSha256') != manifest['source'].get('sha256') or item.get('rights') not in ('owned', 'licensed') or matte.get('reviewStatus') != 'reviewed':
            raise ValueError('Subject layer provenance/review invalid')
        resource_info, mask_info = probe(resource), probe(mask)
        image_stream = next((s for s in resource_info['streams'] if s['codec_type'] == 'video'), None)
        mask_stream = next((s for s in mask_info['streams'] if s['codec_type'] == 'video'), None)
        if not image_stream or image_stream['codec_name'] not in ('png', 'mjpeg', 'webp', 'bmp') or digest(resource) != item['sha256']:
            raise ValueError('Subject resource must be a verified still')
        if not mask_stream or (mask_stream['codec_name'], mask_stream['width'], mask_stream['height'], mask_stream['r_frame_rate'], mask_stream.get('pix_fmt')) != ('ffv1', 1080, 1920, '30/1', 'gray') or abs(float(mask_info['format']['duration']) - manifest['duration']) > 1/30 or digest(mask) != matte['sha256']:
            raise ValueError('Subject matte format/duration/hash mismatch')
        subject_layers.append({'resource': resource, 'resourceSha256': item['sha256'], 'mask': mask, 'maskSha256': matte['sha256'], 'assetId': item['assetId'], 'method': matte['method']})
    overlays = []
    for item in manifest.get('ambientOverlays', []):
        path = pathlib.Path(item['localFile']).resolve(strict=True)
        if not path.is_file() or path.is_symlink() or item.get('kind') not in (None,'overlay') or item.get('rights') not in ('owned','licensed') or item.get('placement') != 'lower-half' or item.get('sha256') != item.get('assetId') or digest(path) != item['sha256']:
            raise ValueError('Overlay source/rights/sha256 invalid')
        probe_result = probe(path)
        visual_streams = [s for s in probe_result['streams'] if s['codec_type']=='video']
        if len(visual_streams) != 1 or visual_streams[0]['codec_name'] not in ('h264','hevc','mpeg4','prores') or float(probe_result['format']['duration']) + 1e-5 < item['sourceOut']:
            raise ValueError('Overlay codec/duration mismatch')
        overlays.append({'path':path,'assetId':item['assetId'],'sha256':item['sha256']})
    music = None
    if manifest.get('audioMix'):
        mix = manifest['audioMix']
        media = pathlib.Path(mix['localFile']).resolve(strict=True)
        if mix.get('rights') not in ('owned', 'licensed') or not 0 < mix.get('gain', 0) <= .18:
            raise ValueError('Music rights/gain invalid')
        details = probe(media)
        stream = next((s for s in details['streams'] if s['codec_type'] == 'audio'), None)
        if stream is None or float(stream.get('duration', details['format']['duration'])) + 1e-6 < mix['sourceOut']:
            raise ValueError('Music missing audio or too short; implicit looping is disabled')
        music = {'path': media, 'sha256': digest(media), 'assetId': mix['assetId'], 'rights': mix['rights'], 'gain': mix['gain']}
    sounds = []
    for item in manifest.get('customSfx', {}).get('assets', []):
        path = pathlib.Path(item['localFile'])
        if path.is_symlink() or not path.is_file() or item.get('kind') != 'sfx' or item.get('rights') not in ('owned', 'licensed') or digest(path) != item.get('sha256') or item.get('assetId') != item.get('sha256'):
            raise ValueError('SFX provenance/hash invalid')
        details = probe(path)
        if not any(s['codec_type'] == 'audio' for s in details['streams']) or any(s['codec_type'] == 'video' and not s.get('disposition', {}).get('attached_pic') for s in details['streams']) or abs(float(details['format']['duration']) - item['duration']) > .03:
            raise ValueError('SFX audio/duration invalid')
        sounds.append({'path': path, 'sha256': item['sha256'], 'assetId': item['assetId']})
    before = digest(source)
    if expected.get('sha256') and expected['sha256'] != before:
        raise ValueError('Source SHA256 mismatch')
    expected_family = manifest['policy']['captions']['font']
    fonts = {'Open Sans': ('OpenSans.ttf', 'OpenSans-Bold.ttf'), 'Inter': ('Inter-Regular.ttf', 'Inter-Bold.ttf'), 'Montserrat': ('Montserrat-Regular.ttf', 'Montserrat-Bold.ttf')}
    if expected_family not in fonts:
        raise ValueError('Unsupported caption font family')
    font, bold_font = [bundle / 'fonts' / name for name in fonts[expected_family]]
    if not font.is_file() or not bold_font.is_file() or not (bundle / 'fonts/OFL.txt').is_file():
        raise ValueError('Supply the configured regular/bold fonts and OFL license')
    for item in (font, bold_font):
        families = subprocess.check_output(['fc-scan', '--format', '%{family}\n', str(item)], text=True).splitlines()
        if expected_family not in families:
            raise ValueError('Font does not match the configured caption family')
    extra_fonts = {}
    if expected_family == 'Montserrat':
        for name, family in [('Montserrat-ExtraBold.ttf', 'Montserrat ExtraBold'), ('Montserrat-BoldItalic.ttf', 'Montserrat'), ('Montserrat-ExtraBoldItalic.ttf', 'Montserrat ExtraBold'), ('Anton-Regular.ttf', 'Anton'), ('AllertaStencil-Regular.ttf', 'Allerta Stencil')]:
            item = bundle / 'fonts' / name
            if not item.is_file() or family not in subprocess.check_output(['fc-scan', '--format', '%{family}\n', str(item)], text=True).replace(',', '\n').splitlines():
                raise ValueError('Required typographic face missing or wrong family: ' + name)
            extra_fonts[name] = digest(item)
        if not (bundle / 'fonts/Anton-OFL.txt').is_file() or not (bundle / 'fonts/AllertaStencil-OFL.txt').is_file():
            raise ValueError('Anton license missing')
    has_audio_graph = '[audio]' in (bundle / 'filter.ffscript').read_text()
    if has_audio_graph != bool(audio):
        raise ValueError('Bundle audio contract does not match source')
    output.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.calma-', suffix='.mp4', dir=output.parent)
    os.close(fd)
    temporary = pathlib.Path(temporary)
    try:
        command = ['ffmpeg', '-v', 'verbose', '-threads', '2', '-i', str(source)]
        for media in bound_media:
            command += ['-i', str(media['path'])]
        for media in illustrations:
            command += ['-loop', '1', '-framerate', '30', '-i', str(media['path'])]
        for layer in subject_layers:
            command += ['-loop', '1', '-framerate', '30', '-i', str(layer['resource']), '-i', str(layer['mask'])]
        for overlay in overlays:
            command += ['-i', str(overlay['path'])]
        if music:
            command += ['-i', str(music['path'])]
        for sound in sounds:
            command += ['-i', str(sound['path'])]
        command += ['-filter_complex_threads', '1', '-filter_complex_script', 'filter.ffscript', '-map', '[video]']
        if audio:
            command += ['-map', '[mixed-audio]' if music or manifest.get('soundEffects', {}).get('events') or manifest.get('customSfx', {}).get('events') or manifest.get('voiceEffects', {}).get('events') or manifest.get('mastering', {}).get('enabled') else '[audio]']
        command += ['-c:v', 'libx264', '-threads', '2', '-preset', 'veryfast', '-crf', '22', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '128k', '-map_metadata', '-1', '-movflags', '+faststart', '-progress', str(output.parent / 'ffmpeg-progress.txt'), '-nostats', '-y', str(temporary)]
        with (bundle / 'render.log').open('w') as log:
            subprocess.run(command, cwd=bundle, stdout=log, stderr=subprocess.STDOUT, check=True)
        result = probe(temporary)
        encoded = next(s for s in result['streams'] if s['codec_type'] == 'video')
        if (encoded['width'], encoded['height'], encoded['r_frame_rate']) != (1080, 1920, '30/1'):
            raise ValueError('Unexpected output dimensions/rate')
        if abs(float(encoded['duration']) - manifest['duration']) > 1/30 + .001:
            raise ValueError('Output duration drift exceeds one frame')
        subprocess.run(['ffmpeg', '-v', 'error', '-i', str(temporary), '-f', 'null', '-'], check=True)
        if any(digest(m['path']) != m['sha256'] for m in bound_media):
            raise ValueError('B-roll source changed during render')
        if any(digest(m['path']) != m['sha256'] for m in illustrations):
            raise ValueError('Illustration changed during render')
        for layer in subject_layers:
            if digest(layer['resource']) != layer['resourceSha256'] or digest(layer['mask']) != layer['maskSha256']:
                raise ValueError('Subject layer changed during render')
        if any(digest(o['path']) != o['sha256'] for o in overlays):
            raise ValueError('Overlay changed during render')
        if music and digest(music['path']) != music['sha256']:
            raise ValueError('Music source changed during render')
        if any(digest(s['path']) != s['sha256'] for s in sounds):
            raise ValueError('SFX changed during render')
        if digest(source) != before:
            raise ValueError('Source changed during render')
        audit = {'version': '1.0', 'sourceSha256': before, 'sourcePreserved': True,
                 'durationPlanned': manifest['duration'], 'durationEncoded': float(encoded['duration']),
                 'output': output.name, 'outputSha256': digest(temporary), 'bytes': temporary.stat().st_size,
                 'video': {'codec': encoded['codec_name'], 'width': encoded['width'], 'height': encoded['height'], 'fps': encoded['r_frame_rate']},
                 'subjectLayers': [{k: v for k, v in layer.items() if k not in ('mask', 'resource')} for layer in subject_layers], 'soundEffects': manifest.get('soundEffects'), 'customSfx': {'assets': [{k: v for k, v in s.items() if k != 'path'} for s in sounds], 'events': manifest.get('customSfx', {}).get('events', [])}, 'audioPresent': bool(audio), 'backgroundAudio': ({k: v for k, v in music.items() if k != 'path'} if music else None), 'broll': [{'assetId': m['assetId'], 'sha256': m['sha256'], 'sourceAudio': False} for m in bound_media], 'ambientOverlays': [{'assetId': m['assetId'], 'sha256': m['sha256'], 'sourceAudio': False, 'visualAcceptance': False} for m in overlays], 'mastering': manifest.get('mastering'), 'voiceEffects': {'version': manifest.get('voiceEffects', {}).get('version'), 'events': manifest.get('voiceEffects', {}).get('events', []), 'humanListeningAccepted': False}, 'captions': len(manifest['captions']), 'illustrations': [{'assetId': m['assetId'], 'sha256': m['sha256'], 'sourceAudio': False} for m in illustrations],
                 'font': {'family': expected_family, 'regularSha256': digest(font), 'boldSha256': digest(bold_font), 'extraFaces': extra_fonts},
                 'ffmpeg': subprocess.check_output(['ffmpeg', '-version'], text=True).splitlines()[0],
                 'fullDecode': 'pass', 'productionReady': False, 'externalCostUSD': 0}
        # Exclusive creation prevents a race from overwriting another output.
        os.link(temporary, output)
        output.with_suffix('.audit.json').write_text(json.dumps(audit, indent=2) + '\n')
        return audit
    finally:
        temporary.unlink(missing_ok=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source', required=True, type=pathlib.Path)
    p.add_argument('--bundle', required=True, type=pathlib.Path)
    p.add_argument('--out', required=True, type=pathlib.Path)
    args = p.parse_args()
    print(json.dumps(render(args.source, args.bundle, args.out), indent=2))


if __name__ == '__main__':
    main()
