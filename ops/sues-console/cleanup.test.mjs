import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createCleanupService} from './cleanup.mjs';

test('scan -> prepare -> explicit consent -> delete, preserving protected projects',t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'sues-cleanup-qa-'));
 t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
 const roots=Object.fromEntries(['store','exports','automation','qa','backups','apt','temp','remotion','chrome'].map(k=>[k,path.join(temp,k)]));
 for(const d of Object.values(roots))fs.mkdirSync(d,{recursive:true});
 const age=p=>fs.utimesSync(p,new Date(Date.now()-10*86400000),new Date(Date.now()-10*86400000));
 const partial=path.join(roots.exports,'failed.part.mp4');fs.writeFileSync(partial,'synthetic');age(partial);
 const newPart=path.join(roots.exports,'recent.part.mp4');fs.writeFileSync(newPart,'recent');
 const project=path.join(roots.qa,'reel-old-20261001');fs.mkdirSync(project);fs.writeFileSync(path.join(project,'project.json'),'{"clips":[]}');age(project);
 const backup=path.join(roots.backups,'update-backup-20261001-foo');fs.mkdirSync(backup);fs.writeFileSync(path.join(backup,'retention.txt'),'keep');
 const link=path.join(roots.exports,'link.part.mp4');fs.symlinkSync(partial,link);
 const cleanup=createCleanupService(roots),s=cleanup.scan();
 assert.equal(s.summary.recommendedCount,1);
 assert.ok(s.items.some(x=>x.path===project&&x.risk==='revisar'));
 assert.ok(s.items.some(x=>x.path===backup&&x.risk==='conservar'));
 assert.ok(!s.items.some(x=>x.path===link));
 assert.ok(!s.items.some(x=>x.path===newPart));
 const id=s.items.find(x=>x.path===partial).id;
 const protectedId=s.items.find(x=>x.path===backup).id;
 assert.throws(()=>cleanup.prepare(s.scanId,[protectedId]),/Seleccion no permitida/);
 const ticket=cleanup.prepare(s.scanId,[id]);
 assert.ok(fs.existsSync(partial));
 assert.throws(()=>cleanup.execute(ticket.approvalId,ticket.token,'BORRAR TODO'),/Confirmacion/);
 assert.throws(()=>cleanup.execute(ticket.approvalId,'0'.repeat(48),ticket.confirmationPhrase),/Token incorrecto/);
 assert.ok(fs.existsSync(partial));
 const result=cleanup.execute(ticket.approvalId,ticket.token,ticket.confirmationPhrase);
 assert.equal(result.results[0].status,'eliminado');
 assert.ok(!fs.existsSync(partial));
 assert.ok(fs.existsSync(project));
 assert.ok(fs.existsSync(backup));
 assert.throws(()=>cleanup.execute(ticket.approvalId,ticket.token,ticket.confirmationPhrase),/aprobacion ya se utilizo/);
 assert.ok(cleanup.markdown(s).includes('Conservar'));
});
test('stale report fails closed before delete',t=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'sues-cleanup-stale-'));
 t.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
 const roots=Object.fromEntries(['store','exports','automation','qa','backups','apt','temp','remotion','chrome'].map(k=>[k,path.join(temp,k)]));
 for(const d of Object.values(roots))fs.mkdirSync(d,{recursive:true});
 const f=path.join(roots.exports,'old.part.mp4');fs.writeFileSync(f,'old');fs.utimesSync(f,new Date(0),new Date(0));
 const clean=createCleanupService(roots),scan=clean.scan(),ticket=clean.prepare(scan.scanId,[scan.items[0].id]);
 fs.appendFileSync(f,'changed');
 assert.throws(()=>clean.execute(ticket.approvalId,ticket.token,ticket.confirmationPhrase),/cambiados/);
 assert.equal(fs.readFileSync(f,'utf8'),'oldchanged');
});
